#!/usr/bin/env node
/**
 * Inline the Solana client into `@genkaku/protocol`'s published artifact.
 *
 * Why this exists: `@solana/web3.js` depends on `rpc-websockets` and `jayson`,
 * which depend on `ws`, which declares `bufferutil` and `utf-8-validate` as
 * OPTIONAL native peers. pnpm installs those peers and then refuses to run
 * their build scripts, so `pnpm add @genkaku/dsh-worker-plugin` fails with
 * ERR_PNPM_IGNORED_BUILDS on every host — the official DSH plugin installer
 * included. Nothing in a consumer's manifest can approve that: the policy lives
 * in the installer's profile, not in this package.
 *
 * So the client stops being a runtime dependency. `tsc` emits `dist/solana.js`
 * importing the registry package; this step rewrites that one file with its
 * dependency graph inlined. Everything else in `dist/` is untouched, and the
 * type declarations still name the real package, because only types cross the
 * boundary.
 *
 *   node scripts/bundle-solana.mjs packages/protocol
 *
 * Runs after `tsc`, so a failed bundle leaves a tree that at least type-checks.
 */
import { build } from 'esbuild'
import { statSync } from 'node:fs'
import { join } from 'node:path'

const [pkgDir] = process.argv.slice(2)
if (pkgDir === undefined) {
  console.error('usage: bundle-solana.mjs <package-dir>')
  process.exit(1)
}

const outfile = join(pkgDir, 'dist', 'solana.js')

await build({
  entryPoints: [join(pkgDir, 'dist', 'solana.js')],
  outfile,
  allowOverwrite: true,
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node22',
  // This package's own modules must stay separate files: the panel imports
  // netconfig and the layout constants directly, and inlining them here would
  // give the running plugin two copies of the same constants.
  external: ['./netconfig.js', 'bs58'],
  banner: {
    js: [
      '// Generated by scripts/bundle-solana.mjs: the Solana client is inlined so',
      '// that installing this package never pulls ws and its native optional peers.',
      '// @solana/web3.js is Apache-2.0; see NOTICE in this package.',
      // The inlined client is CommonJS and reaches for node builtins through
      // `require`, which ESM does not define. A real require tied to this
      // file's location keeps those calls working and resolves them the same
      // way a normal import would.
      "import { createRequire as __genkakuCreateRequire } from 'node:module';",
      'const require = __genkakuCreateRequire(import.meta.url);',
    ].join('\n'),
  },
})

const { size } = statSync(outfile)
console.log(`bundle-solana: dist/solana.js ${size} bytes`)
